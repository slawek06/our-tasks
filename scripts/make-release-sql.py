"""Build the one-file database update for a release.

Run from the project folder:  python3 scripts/make-release-sql.py <first migration number of the release, e.g. 011>
Writes supabase/release-<project name>.sql for each project: a check that it's the right project, the release's
migrations in order, then the privacy check, whose PASS/FAIL table is what the SQL Editor shows at the end.
Paste the file into the SQL Editor of the project it's named after and Run. Safe to run again, like the migrations.
"""
import glob
import os
import re
import sys

PROJECTS = {"our-tasks": "sjtdrnvezorxxdoitszz", "our-tasks-prod": "jwhuaaxrymdqwanwthvg"}

first = sys.argv[1] if len(sys.argv) > 1 else ""
if not re.fullmatch(r"\d{3}", first):
    sys.exit("usage: python3 scripts/make-release-sql.py <first migration number, e.g. 011>")
migrations = [p for p in sorted(glob.glob("supabase/migrations/*.sql")) if os.path.basename(p)[:3] >= first]
if not migrations:
    sys.exit(f"no migrations from {first} on")

for name, ref in PROJECTS.items():
    # The timer job holds this project's address, so it tells the two projects apart (the dashboard's labels don't).
    parts = [f"""-- Our Tasks: database update for project {name} ({ref}), migrations {os.path.basename(migrations[0])[:3]} to {os.path.basename(migrations[-1])[:3]} and the privacy check.
-- Generated by scripts/make-release-sql.py. Paste into that project's SQL Editor and Run. Safe to run again.
-- The result is the privacy check's table: every line should say PASS.
do $$ begin
  if not exists (select 1 from cron.job where jobname = 'our-tasks-notify' and command like '%{ref}%') then
    raise exception 'STOP: this is the wrong Supabase project. This file is for {name}. Nothing was changed.';
  end if;
end $$;
"""]
    for path in [*migrations, "supabase/tests/privacy-check.sql"]:
        parts.append(f"\n-- ======== {os.path.basename(path)} ========\n" + open(path, encoding="utf-8").read())
    out = f"supabase/release-{name}.sql"
    open(out, "w", encoding="utf-8").write("".join(parts))
    print("wrote", out)
