"""Build the one-file database setup for a new Supabase project.

Run from the project folder:  python3 scripts/make-setup-sql.py <project-ref>
Writes supabase/setup-<project-ref>.sql: the schema, every migration in order, the timer pointed at
this project's notify function, and explicit permissions (for projects created with
"Automatically expose new tables" switched off). Paste it into the SQL Editor once and Run.
"""
import glob
import os
import re
import sys

ref = sys.argv[1] if len(sys.argv) > 1 else ""
if not re.fullmatch(r"[a-z0-9]{20}", ref):
    sys.exit("usage: python3 scripts/make-setup-sql.py <20-character project ref>")

parts = [f"-- Our Tasks: complete database setup for project {ref}.\n"
         "-- Generated by scripts/make-setup-sql.py. Run once in the SQL Editor; safe to run again.\n"]
for path in ["supabase/schema.sql", *sorted(glob.glob("supabase/migrations/*.sql"))]:
    sql = open(path, encoding="utf-8").read()
    # The timer must call this project's notify function.
    sql = re.sub(r"https://[a-z0-9]{20}\.supabase\.co/functions/v1/notify", f"https://{ref}.supabase.co/functions/v1/notify", sql)
    if path == "supabase/schema.sql":
        # Make the base schema re-runnable like the migrations.
        sql = sql.replace("create table public.", "create table if not exists public.")
        sql = re.sub(r"create index on public\.(\w+) \(([^)]*)\);",
                     lambda m: f"create index if not exists {m[1]}_{re.sub(r'[^a-z0-9]+', '_', m[2]).strip('_')}_idx on public.{m[1]} ({m[2]});", sql)
        sql = re.sub(r'create policy "([^"]+)"\s+on (public\.\w+)', r'drop policy if exists "\1" on \2;\ncreate policy "\1" on \2', sql)
        sql = sql.replace("alter publication supabase_realtime add table\n  public.tasks, public.comments, public.history, public.lists,\n  public.items, public.catalog, public.config, public.user_state;",
                          "do $$ begin\n  alter publication supabase_realtime add table\n    public.tasks, public.comments, public.history, public.lists,\n    public.items, public.catalog, public.config, public.user_state;\nexception when duplicate_object then null; end $$;")
    parts.append(f"\n-- ======== {os.path.basename(path)} ========\n" + sql)

parts.append("""
-- ======== permissions ========
-- Only signed-in users (subject to the access rules above) and the server functions may use these tables.
-- Anonymous visitors get nothing. push_config stays server-only.
grant usage on schema public to authenticated, service_role;
grant select, insert, update, delete on
  public.tasks, public.comments, public.history, public.lists, public.items, public.catalog,
  public.config, public.user_state, public.push_subscriptions, public.notify_prefs, public.briefings, public.ideas
  to authenticated;
grant all on all tables in schema public to service_role;
""")
out = f"supabase/setup-{ref}.sql"
open(out, "w", encoding="utf-8").write("".join(parts))
print("wrote", out)
